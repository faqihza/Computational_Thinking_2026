# expression and boolean

x = 10

# less than
y = x < 5
print("x < 5 = ", y)

# greater than
y = x > 5
print("x > 5 = ", y)

# less than equal
y = x <= 10
print("x <= 10 = ", y)

# greater than equal
y = x >= 10
print("x >= 10 = ", y)

# equal
y = x == 10
print("x == 10 = ", y)

# not equal
y = x != 10
print("x != 10 = ", y)